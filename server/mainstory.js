const fresh = (run = 1) => ({ run, ch: 0, st: 0, f: {}, b: {}, log: [] });
const clues = ms => CLUES.filter(k => ms.f[k]).length;
const truthReady = ms => clues(ms) >= 5 && !!ms.f.forgive && !!ms.f.joe;
function cond(c, ms, seen = 0) {
  if (c.startsWith('!')) return !cond(c.slice(1), ms, seen);
  let m;
  if ((m = c.match(/^b:(\w+)>=(-?\d+)$/))) return (ms.b[m[1]] || 0) >= +m[2];
  if ((m = c.match(/^run>=(\d+)$/))) return ms.run >= +m[1];
  if ((m = c.match(/^seen>=(\d+)$/))) return seen >= +m[1];
  if ((m = c.match(/^clues>=(\d+)$/))) return clues(ms) >= +m[1];
  if (c === 'truth') return truthReady(ms);
  if (c === 'secret') return ms.run >= 2 && seen >= 3;
  if ((m = c.match(/^love:(\w+)$/))) return ms.f.love === m[1];
  return !!ms.f[c];
}
// resolve lines: drop the ones whose condition fails, swap {love}
function lines(arr, ms, seen, nameOf = id => id) {
  return (arr || []).map(l => Array.isArray(l) ? (cond(l[0], ms, seen) ? l[1] : null) : l).filter(Boolean)
    .map(l => l.replace(/@\{love\}:/g, `@${ms.f.love || ''}:`).replace(/\{love\}/g, nameOf(ms.f.love)));
}
const optsOf = (st, ms, seen) => st.opts.map((o, i) => ({ i, o })).filter(({ o }) => !o.if || cond(o.if, ms, seen));
// apply a choice: flags + bonds; returns the bond changes (for the friendship bonus)
function apply(ms, o) {
  const got = {};
  for (const [k, v] of Object.entries(o.fx?.f || {})) ms.f[k] = v;
  for (const [k0, v] of Object.entries(o.fx?.b || {})) { const k = k0 === '$love' ? ms.f.love : k0; if (!k) continue; ms.b[k] = (ms.b[k] || 0) + v; got[k] = (got[k] || 0) + v; }
  return got;
}
function endingOf(ms, kind) {
  if (kind === 'bus') return 'tragic';
  if (kind === 'true' || kind === 'secret') return kind;
  if (kind === 'love') return (ms.b[ms.f.love] || 0) >= LOVE_NEED ? 'love' : 'happy';
  if (kind === 'friends') return CAST.filter(k => (ms.b[k] || 0) >= FRIEND_NEED).length >= FRIEND_N ? 'friendship' : 'happy';
  return 'happy';
}

